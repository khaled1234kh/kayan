import assert from 'node:assert/strict';
import { BoxGeometry, Group, Mesh, MeshBasicMaterial, Raycaster, Vector3 } from 'three';
import { prepareActorPicking } from '../src/components/actors/actorPicking';
const visual = new Group();
const detailed = new Mesh(new BoxGeometry(20, 60, 15), new MeshBasicMaterial());
detailed.position.y = 30;
detailed.raycast = () => { throw new Error('Detailed picking must not run'); };
visual.add(detailed);
const bounds = prepareActorPicking(visual);
const proxy = new Mesh(new BoxGeometry(...bounds.size), new MeshBasicMaterial({ visible: false }));
proxy.name = 'actor-hit-proxy';
proxy.position.fromArray(bounds.center);
const actor = new Group();
actor.add(visual, proxy);
actor.scale.setScalar(.01);
actor.rotation.y = Math.PI / 2;
actor.updateMatrixWorld(true);
const ray = new Raycaster(new Vector3(0, .3, 2), new Vector3(0, 0, -1));
const hits = ray.intersectObject(actor, true);
assert.equal(hits.length > 0, true);
assert.equal(hits.every((hit) => hit.object === proxy), true);
assert.equal(proxy.material.visible, false);
assert.equal(detailed.geometry.attributes.position.count, 24);
console.log('PASS rotated/scaled actor proxy receives hits, detailed raycast is skipped, visual geometry retained; no rendered acceptance claim.');
